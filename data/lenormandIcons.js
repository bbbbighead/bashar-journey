// 產生一張牌的星座 SVG（金色星點＋髮絲連線）
export function cardConstellation(id) {
  const ic = ICONS[id] || ICONS[16];
  const lines = ic.l.map(([a, b]) => {
    const [x1, y1] = ic.s[a]; const [x2, y2] = ic.s[b];
    return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`;
  }).join('');
  const stars = ic.s.map(([x, y]) => `<circle cx="${x}" cy="${y}" r="1.8"/>`).join('');
  return `<svg class="cst" viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">`
    + `<g class="cst-lines">${lines}</g><g class="cst-stars">${stars}</g></svg>`;
}
